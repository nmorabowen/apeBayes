"""Fast MCMC suite (2026-10-19 review, item D).

Crossed synthetic data, 16 configs × 3 stations × 6 ruptures with known
parameters, fitted with v8 (data generated by v8) and v10 (data generated
by v10). Checks parameter recovery, R², the variance budget, subset labels,
the convergence gate, the stored log-likelihood and model comparison.

Run time: a few minutes (nutpie compile dominates). Deselect with
``-m "not sampling"``.
"""

from __future__ import annotations

import dataclasses
import warnings

import numpy as np
import pytest
from review_helpers import crossed_config, crossed_df, truth

from apeBayes import BayesEpistemicModel, SamplingConfig
from apeBayes.model import CaseRecordModel, RandomSlopesInteractionModel

pytestmark = pytest.mark.sampling

nutpie = pytest.importorskip("nutpie")

SAMPLING = SamplingConfig(draws=600, tune=800, chains=4, seed=11, target_accept=0.95)


def _cfg(sampling: SamplingConfig = SAMPLING):
    return dataclasses.replace(crossed_config(), sampling=sampling)


def _fit(t, builder, *, sampling=SAMPLING, strict=False, name=None):
    m = BayesEpistemicModel(crossed_df(t, noise=True, seed=3), _cfg(sampling), name=name)
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        m.fit(builder=builder, prior_predictive=False, posterior_predictive=False,
              strict=strict)
    return m


@pytest.fixture(scope="module")
def v8_truth():
    t = truth(seed=4)
    t["sigma_eps"] = np.full(16, 0.08)
    return t


@pytest.fixture(scope="module")
def v8_fit(v8_truth):
    return _fit(v8_truth, RandomSlopesInteractionModel(), name="v8")


@pytest.fixture(scope="module")
def v10_truth():
    t = truth(seed=4, case_terms=True)
    t["sigma_eps"] = np.repeat([0.06, 0.08, 0.10, 0.12], 4).reshape(4, 4).T.ravel()
    return t


@pytest.fixture(scope="module")
def v10_fit(v10_truth):
    return _fit(v10_truth, CaseRecordModel(), name="v10")


def _covers(draws, value, q=0.995):
    lo, hi = np.quantile(draws, [1 - q, q])
    return lo <= value <= hi


# ── stored artefacts ─────────────────────────────────────────────────────

@pytest.mark.parametrize("fit", ["v8_fit", "v10_fit"])
def test_log_likelihood_and_attrs_stored(fit, request):
    m = request.getfixturevalue(fit)
    assert "log_likelihood" in m.idata.groups()
    ll = m.idata.log_likelihood["y_obs"]
    assert ll.shape[-1] == m.data.n_obs
    a = m.idata.attrs
    assert a["sampler_used"] == "nutpie" and a["max_treedepth"] == 12
    for k in ("convergence_max_rhat", "convergence_min_ess_bulk", "convergence_converged"):
        assert k in a
    assert a["convergence_max_rhat"] < 1.05


def test_compare_fitted_uses_stored_log_likelihood(v8_fit):
    from apeBayes.model import compare_fitted

    tab = compare_fitted({"a": v8_fit, "b": v8_fit})
    assert set(tab.index) == {"a", "b"}


# ── parameter recovery ───────────────────────────────────────────────────

def test_v8_recovers_parameters(v8_fit, v8_truth):
    p = v8_fit.posterior
    t = v8_truth
    lam = p.lambda_case()
    for c in range(3):
        assert _covers(lam[:, c], t["lambda_case"][c])
    assert _covers(p.sigma_run(), t["sigma_run"])
    assert _covers(p.sigma_inter(), t["sigma_inter"])
    dmu = p.mu_config() - p.mu_config()[:, [15]]
    true_dmu = t["mu_config"] - t["mu_config"][15]
    misses = sum(not _covers(dmu[:, k], true_dmu[k]) for k in range(15))
    assert misses <= 1


def test_v10_recovers_parameters(v10_fit, v10_truth):
    p = v10_fit.posterior
    t = v10_truth
    assert _covers(p.sigma_u_case()[:, 0], t["sigma_u_case"][0])
    assert _covers(p.sigma_v_case()[:, 0], t["sigma_v_case"][0])
    gm_true = np.sqrt(t["sigma_run"] ** 2 + t["sigma_inter"] ** 2
                      + t["sigma_u_case"][3] ** 2 + t["sigma_v_case"][3] ** 2)
    assert _covers(v10_fit.sigma_GM_draws(), gm_true)
    dmu = p.mu_config() - p.mu_config()[:, [15]]
    true_dmu = t["mu_config"] - t["mu_config"][15]
    misses = sum(not _covers(dmu[:, k], true_dmu[k]) for k in range(15))
    assert misses <= 1
    se = np.median(p.draws("sigma_eps_case"), axis=0)
    np.testing.assert_allclose(se, [0.06, 0.08, 0.10, 0.12], atol=0.05)


# ── R², fitted values, variance budget, labels ───────────────────────────

@pytest.mark.parametrize("fit,truth_name", [("v8_fit", "v8_truth"), ("v10_fit", "v10_truth")])
def test_r2_and_residuals(fit, truth_name, request):
    m = request.getfixturevalue(fit)
    t = request.getfixturevalue(truth_name)
    r2 = m.r2_table().iloc[0]
    assert r2["R2_cond_med"] > 0.95
    resid_sd = m.fitted_values()["resid"].std()
    assert resid_sd < 1.5 * np.sqrt(np.mean(t["sigma_eps"] ** 2))


def test_variance_budget_matches_posterior(v8_fit):
    p = v8_fit.posterior
    vb = v8_fit.variance_budget_table().set_index("component")
    lam = p.lambda_case()[:, v8_fit.data.case_mapping()[2]]
    want = np.median(np.mean(lam ** 2, axis=1) * p.sigma_run() ** 2)
    assert vb.loc["Run dispersion λ²σ²_run", "var_med"] == pytest.approx(want)
    assert vb["pct_mean"].sum() == pytest.approx(100.0)


def test_variance_component_labels_after_fit(v10_fit):
    p = v10_fit.posterior
    vc = v10_fit.variance_component_table(configs=["4D", "1A"]).set_index("component")
    se = p.sigma_eps()
    assert vc.loc["sigma_eps[4D]", "med"] == pytest.approx(np.median(se[:, 15]))
    assert vc.loc["sigma_eps[1A]", "med"] == pytest.approx(np.median(se[:, 0]))


def test_decision_report_on_fit(v10_fit):
    rep = v10_fit.decision_report(record_marginal=True, rope_abs=np.log(1.2))
    assert rep["converged"].nunique() == 1
    assert rep["converged"].iloc[0] == v10_fit.converged
    assert set(rep["decision_new"]) <= {"equivalent", "inequivalent", "undecided"}


# ── convergence gate ─────────────────────────────────────────────────────

def test_convergence_gate_raises_on_short_run(v8_truth):
    short = SamplingConfig(draws=30, tune=30, chains=2, seed=1)
    with pytest.raises(RuntimeError, match="convergence gate"):
        _fit(v8_truth, RandomSlopesInteractionModel(), sampling=short, strict=True)


# ── leave-one-rupture-out ────────────────────────────────────────────────

def test_leave_one_rupture_out_runs(v8_truth):
    from apeBayes.model import leave_one_group_out

    small = SamplingConfig(draws=300, tune=400, chains=2, seed=5, target_accept=0.95)
    df = crossed_df(v8_truth, noise=True, seed=3)
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        res = leave_one_group_out(df, _cfg(small), RandomSlopesInteractionModel(),
                                  folds=["rup_2"], max_draws=200)
    assert len(res) == 1 and np.isfinite(res["lpd"].iloc[0])
    assert res["n_obs"].iloc[0] == 48


# ── bundle round trip keeps the v10 builder ──────────────────────────────

def test_v10_bundle_roundtrip(v10_fit, tmp_path):
    path = v10_fit.save(tmp_path / "v10")
    m2 = BayesEpistemicModel.load(path)
    assert isinstance(m2.builder, CaseRecordModel)
    np.testing.assert_allclose(m2.sigma_GM_draws(), v10_fit.sigma_GM_draws())
    assert m2.converged == v10_fit.converged
